#!/usr/bin/env python3
"""Generate stable CLI and configuration references.

CLI rows come from Typer/Click metadata. Configuration defaults and provider
maps come from shared runtime constants; explanatory policy text remains
reviewed in this generator. Use --check in CI to detect drift.
"""

from __future__ import annotations

import argparse
from pathlib import Path
import sys

import click
from typer.main import get_command

ROOT = Path(__file__).resolve().parents[1]
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))


def markdown_cell(value: object) -> str:
    """Return a deterministic Markdown table cell across operating systems."""
    text = value.as_posix() if isinstance(value, Path) else str(value)
    return " ".join(text.replace("|", "\\|").split()) or "—"


def option_type(option: click.Option) -> str:
    if isinstance(option.type, click.Choice):
        return markdown_cell(" | ".join(str(choice) for choice in option.type.choices))
    return option.type.name.upper()


def option_rows(command: click.Command) -> list[str]:
    rows = []
    for parameter in command.params:
        if not isinstance(parameter, click.Option) or parameter.hidden:
            continue
        flags = ", ".join(
            f"`{flag}`" for flag in (*parameter.opts, *parameter.secondary_opts)
        )
        default = "required" if parameter.required else markdown_cell(parameter.default)
        rows.append(
            f"| {flags} | {option_type(parameter)} | {default} | "
            f"{markdown_cell(parameter.help or '')} |"
        )
    return rows


def command_section(title: str, command: click.Command) -> str:
    description = markdown_cell(command.help or "")
    rows = option_rows(command)
    table = "\n".join(rows) if rows else "| — | — | — | No options |"
    return (
        f"## {title}\n\n{description}\n\n"
        "| Option | Type | Default | Purpose |\n"
        "|---|---|---|---|\n"
        f"{table}"
    )


def cli_reference() -> str:
    from pocarchitect.cli import app

    root_command = get_command(app)
    sections = [command_section("Main command", root_command)]
    sections.extend(
        command_section(f"Command: `{name}`", command)
        for name, command in root_command.commands.items()
    )
    commands = "\n".join(
        f"| `{name}` | {markdown_cell(command.help or '')} |"
        for name, command in root_command.commands.items()
    )
    return (
        "# CLI Reference\n\n"
        "Generated directly from Typer/Click command metadata by "
        "`python scripts/generate_docs.py`; it does not depend on terminal layout or platform path separators.\n\n"
        + "\n\n".join(sections)
        + "\n\n## Commands\n\n"
        "| Command | Purpose |\n"
        "|---|---|\n"
        f"{commands}" + "\n\n## Safe examples\n\n"
        "```text\n"
        "python -m pocarchitect preflight --provider local --offline\n"
        "python -m pocarchitect --url https://github.com/example/poc --no-ingest --dry-run --no-color\n"
        "python -m pocarchitect --format json --no-color batch-status --batch-state reports/batch_progress.json\n"
        "```\n"
        "\nRoot options such as `--format` and `--no-color` must appear before a "
        "subcommand name. Main-command options such as `--url` remain on the main command.\n"
    )


def config_reference() -> str:
    from pocarchitect.config import (
        DEFAULT_LOCAL_BASE_URL,
        DEFAULT_MODELS,
        DEFAULT_PROVIDER,
        DEFAULT_RISK_LEVEL,
        DEFAULT_TARGET_OS,
        DEFAULT_TEMPERATURE,
        PROVIDER_KEY_NAMES,
    )

    credential_rows = "\n".join(
        f"| `{environment_name}` | string | `--provider {provider}` real run | "
        "None | Provider-issued credential | Yes | `pocarchitect/config.py` |"
        for provider, environment_name in PROVIDER_KEY_NAMES.items()
    )
    model_rows = "\n".join(
        f"| `{provider}` | `{model}` |" for provider, model in DEFAULT_MODELS.items()
    )
    provider_choices = ", ".join(f"`{provider}`" for provider in DEFAULT_MODELS)

    return f"""# Configuration Reference

Generated by `python scripts/generate_docs.py`. Provider maps and effective
defaults are imported from `pocarchitect/config.py`; option declarations are
cross-checked through the generated [CLI Reference](cli-reference.md).
Explanatory policy text and sensitivity classifications are maintained in
`scripts/generate_docs.py` and still require review.

## Provider credentials

`pocarchitect` loads a `.env` file from the current working directory without
overriding already-set environment variables. For cloud providers, a non-empty,
non-placeholder environment value takes precedence over the value in `.env`.
There is no configuration file other than `.env`.

| Setting | Type | Required when | Default | Allowed values | Sensitive | Source location |
|---|---|---|---|---|---|---|
{credential_rows}
| `IN_DOCKER` | string | Optional | Unset | Any set value selects `/reports` as the default output directory | No | `pocarchitect/config.py` |

Place provider keys in a local `.env` file. Never commit `.env`, print its
values, or include credentials in reports or issue diagnostics. `--dry-run`
and `preflight --offline` do not require a provider key.

## Provider and model defaults

| Provider | Default model |
|---|---|
{model_rows}

The current CLI provider choices are {provider_choices}. Claude and Gemini
wording in the packaged prompt describes prompt portability, not additional
named CLI providers. Other OpenAI-compatible services are configured through
`--provider local --base-url <URL>` and must support the requests the operator
chooses to make.

## Command configuration

| Setting | Type | Required when | Default | Allowed values | Sensitive | Source location |
|---|---|---|---|---|---|---|
| `--provider`, `-p` | choice | Any real run | `{DEFAULT_PROVIDER}` | {provider_choices} | No | `pocarchitect/cli.py` |
| `--model`, `-m` | string | Optional | Provider-specific | Any model name accepted by the selected provider | No | `pocarchitect/cli.py` |
| `--temperature`, `-t` | float | Optional | `{DEFAULT_TEMPERATURE}` | Any float accepted by the provider | No | `pocarchitect/cli.py` |
| `--base-url` | string | Optional for `local` | `{DEFAULT_LOCAL_BASE_URL}` | OpenAI-compatible endpoint URL | No | `pocarchitect/config.py` |
| `--output-dir` | path | Optional | `reports/` (or `/reports` when `IN_DOCKER` or `/.dockerenv` is present) | Writable directory | No | `pocarchitect/config.py` |
| `--batch-state` | path | Optional for batch operations | `reports/batch_progress.json` | JSON state-file path | No | `pocarchitect/cli.py` |
| `--yes` | flag | Noninteractive source transfer or batch reset | Off | Present or absent | No | `pocarchitect/cli.py` |
| `--format` | choice | Optional | `text` | `text`, `json` | No | `pocarchitect/cli.py` |
| `--no-color` | flag | Optional | Off | Present or absent | No | `pocarchitect/cli.py` |
| `--risk-level` | string | Optional | `{DEFAULT_RISK_LEVEL}` | Free text; no CLI validation | No | `pocarchitect/cli.py` |
| `--target-os` | string | Optional | `{DEFAULT_TARGET_OS}` | Free text; no CLI validation | No | `pocarchitect/cli.py` |
| `--include-mitigations` / `--no-mitigations` | flag | Optional | On | Use `--no-mitigations` to omit mitigation instructions | No | `pocarchitect/cli.py` |
| `--no-ingest` | flag | Optional | Off | Present or absent | No | `pocarchitect/cli.py` |

For a complete option list, see [CLI Reference](cli-reference.md). Root
`--format` and `--no-color` options apply to `batch-status` and `batch-reset`
when placed before the subcommand, for example:

```text
pocarchitect --format json --no-color batch-status --batch-state reports/batch_progress.json
```

Automatic preflight checks the same resolved report directory that the real
run will use, including an explicit `--output-dir`. The standalone `preflight`
command also accepts `--output-dir`. `--dry-run` bypasses automatic preflight
entirely; run `preflight --offline` when installation checks are required.
"""


def write_or_check(path: Path, content: str, check: bool) -> bool:
    if check:
        return path.exists() and path.read_text(encoding="utf-8") == content
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(content, encoding="utf-8")
    return True


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    results = [
        write_or_check(ROOT / "docs" / "cli-reference.md", cli_reference(), args.check),
        write_or_check(
            ROOT / "docs" / "configuration-reference.md",
            config_reference(),
            args.check,
        ),
    ]
    if args.check and not all(results):
        print("Generated documentation is stale. Run: python scripts/generate_docs.py")
        return 1
    print(
        "Generated documentation is up to date."
        if args.check
        else "Generated documentation."
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
